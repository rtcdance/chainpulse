// bridgeHandshakeReadLimit bounds the relayed upstream handshake body so a
// misbehaving upstream cannot stream unbounded bytes into the gateway response.
const bridgeHandshakeReadLimit = 8 << 10

// tryForwardSubscriptionUpgrade bridges a WebSocket subscription upgrade to an
// available upstream api-service, where the MQ-fed subscription hub lives, and
// returns true when the request was fully handled (forwarded or rejected). It
// returns false only when no upstream endpoints are configured, preserving the
// existing local in-process handler path (monolithic full surface and tests).
func (gri *GatewayRouterIntegration) tryForwardSubscriptionUpgrade(w http.ResponseWriter, wrapped http.ResponseWriter, r *http.Request, route *Route) bool {
	if len(gri.upstreamQueryEndpoints) == 0 {
		return false
	}
	if !strings.EqualFold(r.Header.Get("Upgrade"), "websocket") {
		return false
	}
	h := gri.subscriptionHandler
	if h == nil {
		(&APIError{Code: "INTERNAL_SERVER_ERROR", Message: "Subscription handler not configured", Status: http.StatusInternalServerError}).WriteHTTP(w)
		return true
	}
	// Same pre-upgrade policy as the local path so a bridged request is
	// rejected before any upstream dial or local hijack.
	if !h.initialized {
		http.Error(w, "Handler not initialized", http.StatusInternalServerError)
		return true
	}
	if !h.allowSubscriptionRequest(w, r) {
		return true
	}
	if h.tokenValidator != nil && !h.validateWSAuth(r) {
		http.Error(w, "Unauthorized", http.StatusUnauthorized)
		return true
	}
	if _, _, _, err := parseResumeCursor(r); err != nil {
		http.Error(w, "Invalid last_event_id", http.StatusBadRequest)
		return true
	}

	endpoint, ok := gri.availableSubscriptionUpstream(route)
	if !ok {
		respondGatewaySubscriptionBridgeError(w, http.StatusBadGateway)
		return true
	}
	gri.bridgeSubscription(wrapped, r, endpoint)
	return true
}

// availableSubscriptionUpstream picks the first health-gated upstream handler
// attached to the subscription route, falling back to the first configured
// endpoint when no handler has been attached yet.
func (gri *GatewayRouterIntegration) availableSubscriptionUpstream(route *Route) (string, bool) {
	if route != nil {
		for _, handler := range route.GetHandlers() {
			if handler != nil && handler.IsAvailable() && strings.TrimSpace(handler.Endpoint) != "" {
				return handler.Endpoint, true
			}
		}
	}
	for _, endpoint := range gri.upstreamQueryEndpoints {
		if strings.TrimSpace(endpoint) != "" {
			return endpoint, true
		}
	}
	return "", false
}

// bridgeSubscription dials the upstream WebSocket, relays upstream handshake
// status codes to the client before any local upgrade, then pumps frames in
// both directions until either side closes.
func (gri *GatewayRouterIntegration) bridgeSubscription(w http.ResponseWriter, r *http.Request, endpoint string) {
	target, err := resolveSubscriptionBridgeTarget(endpoint, r)
	if err != nil {
		gri.logger.Error("Invalid subscription upstream endpoint", "endpoint", endpoint, "error", err.Error())
		respondGatewaySubscriptionBridgeError(w, http.StatusBadGateway)
		return
	}

	header := make(http.Header, len(r.Header))
	for key, values := range r.Header {
		switch http.CanonicalHeaderKey(key) {
		case "Connection", "Upgrade", "Host", "Sec-Websocket-Key", "Sec-Websocket-Version", "Sec-Websocket-Extensions", "Sec-Websocket-Protocol":
			// Hop-by-hop and websocket handshake headers are regenerated by the
			// dialer; everything else (auth, Origin, Last-Event-ID) is forwarded.
			continue
		default:
			header[key] = values
		}
	}
	for key, value := range gri.upstreamQueryHealthHeaders {
		header.Set(key, value)
	}

	upstreamConn, resp, err := websocket.DefaultDialer.DialContext(r.Context(), target, header)
	if err != nil {
		if resp != nil {
			// The upstream rejected the handshake (auth, cursor validation...):
			// relay its status verbatim before the local upgrade so the client
			// sees the real rejection instead of a half-open gateway socket.
			defer func() {
				if closeErr := resp.Body.Close(); closeErr != nil {
					gri.logger.Debug("subscription bridge handshake body close error", "error", closeErr.Error())
				}
			}()
			body, _ := io.ReadAll(io.LimitReader(resp.Body, bridgeHandshakeReadLimit))
			if contentType := resp.Header.Get("Content-Type"); contentType != "" {
				w.Header().Set("Content-Type", contentType)
			}
			w.WriteHeader(resp.StatusCode)
			_, _ = w.Write(body)
			gri.metrics.RecordCounter("gateway_subscription_bridge_handshake_rejected", 1, map[string]string{
				"status": fmt.Sprintf("%d", resp.StatusCode),
			})
			return
		}
		gri.logger.Error("Subscription bridge upstream dial failed", "endpoint", endpoint, "error", err.Error())
		gri.metrics.RecordCounter("gateway_subscription_bridge_dial_failed", 1, nil)
		respondGatewaySubscriptionBridgeError(w, http.StatusBadGateway)
		return
	}

	upgrader := websocket.Upgrader{
		ReadBufferSize:  1024,
		WriteBufferSize: 1024,
		CheckOrigin:     gri.subscriptionHandler.checkOrigin,
	}
	clientConn, err := upgrader.Upgrade(w, r, nil)
	if err != nil {
		// Upgrade already wrote the HTTP error response.
		_ = upstreamConn.Close()
		return
	}

	gri.logger.Info("Subscription bridge established", "endpoint", endpoint, "path", r.URL.Path, "remoteAddr", r.RemoteAddr)
	gri.metrics.RecordCounter("gateway_subscription_bridge_connected", 1, nil)

	var once sync.Once
	closeBoth := func() {
		once.Do(func() {
			_ = clientConn.Close()
			_ = upstreamConn.Close()
		})
	}
	clientDone := make(chan struct{})
	go func() {
		defer close(clientDone)
		for {
			messageType, message, readErr := clientConn.ReadMessage()
			if readErr != nil {
				return
			}
			if writeErr := upstreamConn.WriteMessage(messageType, message); writeErr != nil {
				return
			}
		}
	}()

	for {
		_ = upstreamConn.SetReadDeadline(time.Time{})
		messageType, message, readErr := upstreamConn.ReadMessage()
		if readErr != nil {
			break
		}
		_ = clientConn.SetWriteDeadline(time.Now().Add(10 * time.Second))
		if writeErr := clientConn.WriteMessage(messageType, message); writeErr != nil {
			break
		}
	}
	closeBoth()
	<-clientDone
}

// resolveSubscriptionBridgeTarget rewrites an http(s) upstream endpoint into
// the ws(s) URL of the same subscription path and query the client requested.
func resolveSubscriptionBridgeTarget(endpoint string, r *http.Request) (string, error) {
	parsed, err := url.Parse(strings.TrimSpace(endpoint))
	if err != nil {
		return "", fmt.Errorf("parse endpoint %q: %w", endpoint, err)
	}
	if parsed.Host == "" {
		return "", fmt.Errorf("endpoint %q has no host", endpoint)
	}
	var scheme string
	switch parsed.Scheme {
	case "https", "wss":
		scheme = "wss"
	case "http", "ws":
		scheme = "ws"
	default:
		return "", fmt.Errorf("endpoint %q has unsupported scheme %q", endpoint, parsed.Scheme)
	}
	target := &url.URL{
		Scheme:   scheme,
		Host:     parsed.Host,
		Path:     r.URL.Path,
		RawQuery: r.URL.RawQuery,
	}
	return target.String(), nil
}

// respondGatewaySubscriptionBridgeError mirrors respondGatewayQueryBridgeError
// for subscription routes: an explicit gateway error instead of upgrading the
// client into a hub with no MQ input.
func respondGatewaySubscriptionBridgeError(w http.ResponseWriter, statusCode int) {
	payload := map[string]any{
		"error":      "subscription_upstream_unavailable",
		"message":    "api-gateway could not reach an upstream api-service for this subscription request",
		"statusCode": statusCode,
		"timestamp":  time.Now().Unix(),
		"meta": map[string]any{
			"bridgePosture":    "subscription-bridge-unavailable",
			"responseBoundary": "gateway-subscription-bridge",
		},
	}
	body, _ := json.Marshal(payload)
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(statusCode)
	_, _ = w.Write(body)
}
